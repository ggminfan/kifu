/**
 * Render the Kifu app icon into desktop/assets/Kifu.iconset: the PNG sizes iconutil expects
 * (Electrobun turns the folder into AppIcon.icns at build time). The artwork is appIconSvg() in
 * src/shared/brand.ts (the drawn wordmark), written out as desktop/assets/kifu-icon.svg (64 px
 * and up) and kifu-icon-small.svg (K and the spark, below). macOS only: headless Google Chrome
 * renders the SVGs (a throwaway profile, mock keychain: no prompts, the user's own profile is not
 * touched), sips scales, iconutil checks that the set converts.
 *
 *   pnpm icons                 CHROME_BIN=… to use another Chromium
 */
import { execFileSync, spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { appIconSvg } from '../src/shared/brand';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const assets = path.join(root, 'desktop', 'assets');
const out = path.join(assets, 'Kifu.iconset');
const chrome = process.env.CHROME_BIN ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function render(svg: string, png: string): Promise<void> {
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'kifu-chrome-'));
  const child = spawn(
    chrome,
    [
      '--headless=new',
      '--disable-gpu',
      '--hide-scrollbars',
      '--no-first-run',
      '--no-default-browser-check',
      '--use-mock-keychain',
      '--password-store=basic',
      '--disable-extensions',
      '--disable-component-update',
      '--disable-background-networking',
      `--user-data-dir=${profile}`,
      '--default-background-color=00000000',
      '--force-device-scale-factor=1',
      '--window-size=1024,1024',
      `--screenshot=${png}`,
      `file://${svg}`,
    ],
    { stdio: 'ignore' },
  );
  try {
    // done once the file exists and its size holds still (Chrome may linger after writing it)
    let last = -1;
    for (const end = Date.now() + 60_000; ; ) {
      const size = fs.existsSync(png) ? fs.statSync(png).size : 0;
      if (size > 0 && size === last) break;
      if (Date.now() > end) throw new Error(`Chrome did not render ${path.basename(svg)} (CHROME_BIN=${chrome})`);
      last = size;
      await sleep(250);
    }
  } finally {
    child.kill();
    await sleep(300);
    fs.rmSync(profile, { recursive: true, force: true });
  }
  const dims = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', png], { encoding: 'utf8' });
  if (!/pixelWidth: 1024/.test(dims) || !/pixelHeight: 1024/.test(dims)) throw new Error(`${path.basename(svg)} rendered at the wrong size:\n${dims}`);
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'kifu-icons-'));
try {
  // the sources, from the shared artwork (edit src/shared/brand.ts, not these files)
  const note = '<!-- Copyright (c) 2026 Liam. Brand artwork: see ../../TRADEMARKS.md. Generated by `pnpm icons` from src/shared/brand.ts. -->\n';
  fs.writeFileSync(path.join(assets, 'kifu-icon.svg'), `${note}${appIconSvg()}\n`);
  fs.writeFileSync(path.join(assets, 'kifu-icon-small.svg'), `${note}${appIconSvg({ small: true })}\n`);
  const big = path.join(tmp, 'icon.png');
  const small = path.join(tmp, 'icon-small.png');
  await render(path.join(assets, 'kifu-icon.svg'), big);
  await render(path.join(assets, 'kifu-icon-small.svg'), small);

  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  const images: Array<[name: string, px: number, from: string]> = [
    ['icon_16x16.png', 16, small],
    ['icon_16x16@2x.png', 32, small],
    ['icon_32x32.png', 32, small],
    ['icon_32x32@2x.png', 64, big],
    ['icon_128x128.png', 128, big],
    ['icon_128x128@2x.png', 256, big],
    ['icon_256x256.png', 256, big],
    ['icon_256x256@2x.png', 512, big],
    ['icon_512x512.png', 512, big],
    ['icon_512x512@2x.png', 1024, big],
  ];
  for (const [name, px, from] of images) {
    const dest = path.join(out, name);
    if (px === 1024) fs.copyFileSync(from, dest);
    else execFileSync('sips', ['-z', String(px), String(px), from, '--out', dest], { stdio: 'ignore' });
  }
  // Electrobun runs the same conversion at build time: it must succeed
  const icns = path.join(tmp, 'check.icns');
  execFileSync('iconutil', ['-c', 'icns', out, '-o', icns]);
  console.log(`desktop/assets/Kifu.iconset: ${images.length} images, converts to a ${(fs.statSync(icns).size / 1024).toFixed(0)} KB .icns`);
} finally {
  fs.rmSync(tmp, { recursive: true, force: true });
}
